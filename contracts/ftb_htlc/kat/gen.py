#!/usr/bin/env python3
# Generator for the FtbHtlc cross-chain differential KAT. One source of truth, two outputs:
#   kat/vectors.json        - consumed by the N3 neotest harness (ftb_htlc_kat_test.go)
#   evm/test/KatVectors.sol - imported by the Neo X Foundry harness (FtbHtlcKat.t.sol)
# Both outputs are written together, so the two harnesses are provably the same vectors.
# preimage is a 32-byte value; hashlock = SHA-256(preimage). Regenerate: python3 kat/gen.py
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))        # .../contracts/ftb_htlc/kat
FTB_HTLC = os.path.dirname(HERE)                          # .../contracts/ftb_htlc


def sha(b):
    return hashlib.sha256(b).digest()


def hx(b):
    return "0x" + b.hex()


def mk(label, amount, scenario):
    pre = sha(label.encode())            # 32-byte preimage
    hl = sha(pre)                        # hashlock = sha256(preimage)
    return {"amount": amount, "hashlock": hx(hl), "preimage": hx(pre), "scenario": scenario}


VECTORS = [
    mk("ftb-kat-claim-dust", 1, "claim"),
    mk("ftb-kat-claim-mid", 1000, "claim"),
    mk("ftb-kat-claim-large", 1000000, "claim"),
    mk("ftb-kat-refund-dust", 1, "refund"),
    mk("ftb-kat-refund-mid", 1000, "refund"),
]
WRONG = hx(sha(b"ftb-kat-wrong"))

NOTE = ("Shared cross-chain KAT vectors for FtbHtlc. preimage is 32 bytes; "
        "hashlock = SHA-256(preimage). The N3 neotest harness and the Neo X Foundry harness "
        "both consume these vectors and must settle every one identically. "
        "Generated by kat/gen.py together with evm/test/KatVectors.sol - do not edit by hand.")


def write_json():
    doc = {"note": NOTE, "wrongPreimage": WRONG, "vectors": VECTORS}
    path = os.path.join(HERE, "vectors.json")
    with open(path, "w") as f:
        f.write(json.dumps(doc, indent=2) + "\n")
    return path


def write_sol():
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by kat/gen.py together with kat/vectors.json - do not edit by hand.",
        "pragma solidity 0.8.26;",
        "",
        "// The shared differential-KAT vectors, as constants, so the Foundry harness needs no",
        "// file I/O and stays dependency-free. Mirrors kat/vectors.json exactly.",
        "library KatVectors {",
        f"    bytes32 internal constant WRONG_PREIMAGE = {WRONG};",
        f"    uint256 internal constant COUNT = {len(VECTORS)};",
        "",
        "    // Returns (amount, hashlock, preimage, isClaim) for vector i.",
        "    function get(uint256 i) internal pure returns (uint256, bytes32, bytes32, bool) {",
        # The return lines exceed the formatter's line length; a disable-start/end block keeps
        # `forge fmt` from touching them, so the generated file stays byte-stable.
        "        // forgefmt: disable-start",
    ]
    for idx, v in enumerate(VECTORS):
        is_claim = "true" if v["scenario"] == "claim" else "false"
        lines.append(
            f'        if (i == {idx}) return ({v["amount"]}, {v["hashlock"]}, {v["preimage"]}, {is_claim});'
        )
    lines += [
        "        // forgefmt: disable-end",
        "        revert();",
        "    }",
        "}",
    ]
    path = os.path.join(FTB_HTLC, "evm", "test", "KatVectors.sol")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


if __name__ == "__main__":
    j = write_json()
    s = write_sol()
    print("wrote", j)
    print("wrote", s)
